# 민감·악의 의도 차단. 핵심 원칙(실데이터 79개 FAQ로 검증):
#   - 민감 명사(계정/비밀번호/성적/출결/권한)는 정상 질문에도 흔히 등장하므로
#     '단독으로는 절대 차단하지 않는다'. 반드시 '대상/민감명사 + 악의 행위'가
#     AND로 결합될 때만 차단한다. 이 덕분에 "비밀번호 잊음 안내", "부정 출결 방지",
#     "정답 수정", "성적 일괄 등록" 같은 정상 질문이 전부 통과한다.
#   - 편집 동사(수정/변경/바꾸)는 광범위해 정상과 겹치므로, 은밀성 한정자
#     (몰래/무단/불법/들키지 않게)가 동반될 때만 차단한다(P2).
#   - FAQ가 확장되면 tests/test_guardrail.py 의 오탐 회귀 테스트를 다시 돌릴 것.
_UNSAFE_PATTERNS = [
    # P0 계정 탈취: 대상(다른/남/타인/동료/타교수) + 자격증명/권한 + 악의 동사
    r"(?:다른|남(?:의)?|타인|타\s*교수|동료)"
    r".{0,20}?(?:계정|아이디|비밀\s*번호|비번|패스워드|password|로그인\s*정보|로그인\s*권한|권한)"
    r".{0,15}?(?:알아내|빼내|빼돌|탈취|훔치|뺏|가로채|크랙|뚫|캐내|취득|획득)",
    # P1 어순 반대: 악의 동사 + 자격증명/권한
    r"(?:탈취|훔치|빼내|가로채|해킹|크랙)"
    r".{0,15}?(?:계정|아이디|비밀\s*번호|비번|패스워드|password|로그인\s*정보|권한)",
    # P2 은밀/부정 조작: 은밀성 한정자가 반드시 동반될 때만 광범위 편집동사 차단
    r"(?:몰래|부정\s*하게|무단|불법(?:으로|적)|들키지\s*않게|들키지\s*않고|안\s*걸리게|티\s*안\s*나게)"
    r".{0,20}?(?:조작|변조|위조|바꾸|바꿔|변경|수정|올리|내리|속이|날조|빼내)",
    # P3 데이터 무결성: 민감 데이터 + 명백 악의어(조작/변조/위조/날조). 수정/변경은 제외
    r"(?:성적|점수|학점|출결|출석|기록|로그|데이터|평점|등급)"
    r".{0,12}?(?:조작|변조|위조|날조)",
    # P4 시스템 침해: 관리자/시스템/서버/DB + 침해 동사
    r"(?:관리자|admin|시스템|서버|\bDB\b|데이터\s*베이스)"
    r".{0,12}?(?:우회|뚫|해킹|침투|침입|털|크랙|탈취|권한\s*상승)",
    # P5 단독 악의어: 정상 FAQ에 0건이라 단독 차단해도 오탐 0
    r"(?:해킹|hacking|크래킹|cracking|sql\s*injection|백도어|backdoor|취약점\s*공격|권한\s*상승|권한\s*탈취|버퍼\s*오버플로)",
    # P6 인증·보안 우회: 우회/무력화 + 인증/보안/제한
    r"(?:우회|무력화|뚫는\s*법|뚫는\s*방법|풀어내)"
    r".{0,15}?(?:인증|로그인|보안|권한|제한|차단|접근\s*제어)",
    # P7 어순 반대: 인증/보안/제한 + 우회/무력화
    r"(?:인증|로그인|보안|권한|제한|차단|접근\s*제어)"
    r".{0,15}?(?:우회|무력화|뚫는\s*법|뚫는\s*방법)",
]
_UNSAFE_RES = [re.compile(p, flags=re.IGNORECASE) for p in _UNSAFE_PATTERNS]


def is_unsafe_request(query: str) -> bool:
    """민감·악의 의도 요청인지 검사. 검색 전에 결정적으로 차단하기 위함.
    민감 명사 단독이 아니라 '대상/민감명사 + 악의 행위' 결합일 때만 True."""
    q = query.strip()
    if not q:
        return False
    for r in _UNSAFE_RES:
        if r.search(q):
            return True
    return False
